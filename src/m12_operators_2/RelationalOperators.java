package m12_operators_2;

public class RelationalOperators {
    static void main() {
        int x = 0;

        System.out.println(x<1);
        System.out.println(x>0);

        System.out.println(x>=0);
        System.out.println(x<=10);

        System.out.println(x>=25);

        System.out.println(x==0);
        System.out.println(x!=0);
    }
}
