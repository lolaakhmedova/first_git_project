package m11_operators_1;

public class ArithmeticOperators {
    static void main() {
        System.out.println(10+5);
        System.out.println(10-5);
        System.out.println(10/5);
        System.out.println(10d/4);
        System.out.println(10/4.0);
        System.out.println(10*4);
        System.out.println(10%4);
        System.out.println(10%5);
        System.out.println(9%2);
        System.out.println(1234%10);
    }
}
