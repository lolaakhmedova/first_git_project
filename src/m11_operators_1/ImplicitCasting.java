package m11_operators_1;

public class ImplicitCasting {
    static void main() {
      byte num1=25;
      int num2=num1;//implicit casting

        System.out.println("num1 = "+num1);
        System.out.println("num2 = "+num2);

       double num3;
       int num4 = 15;

       num3=num4;
        System.out.println("num3= " +num3);
        System.out.println("num4= " +num4);


    }
}
