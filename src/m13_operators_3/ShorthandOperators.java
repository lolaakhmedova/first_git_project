package m13_operators_3;

public class ShorthandOperators {
    static void main() {
      int x=5;
        System.out.println(x);
        x += 5;
        System.out.println(x);


        int y=10;
        System.out.println(y);
        y -= 4;
        System.out.println(y);

        int z=3;
        System.out.println(z);
        z *= 3;
        System.out.println(z);

        int a=15;
        System.out.println(a);
        a/=3;
        System.out.println(a);


        int b=10;
        System.out.println(b);
        b%=3;
        System.out.println(b);

        double c=4.5;
        System.out.println(c);
        c +=10;
        System.out.println(c);


    }
}






