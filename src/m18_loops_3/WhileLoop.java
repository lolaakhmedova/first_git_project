package m18_loops_3;

public class WhileLoop {
    static void main() {
        for (int i = 0; i <11 ; i++) {
            System.out.print(i + " ");
        }
        System.out.println();
        int j=0;
        while(j<11){
            System.out.print(j+" ");
            j++;
        }
    }
}
