package m21_methods_2;

public class OddOrEven {
    static void main() {

        OddOrEven(45);
    }



    public static void OddOrEven(int num){

        if (num % 2==0){
            System.out.println("Number is even");
        }else {
            System.out.println("Number is odd");
        }
    }

}
