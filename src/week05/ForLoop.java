package week05;

public class ForLoop {
    static void main() {
        for (int i=1; i<=10; i++){
            System.out.println("Hello Friends!");

        }

        for (int i = 1; i <= 5; i++) {
            System.out.print("java - " + i + " ");
        }

        for (int i = 8; i >= 1; i--) {
            System.out.println("selenium - " + i);
        }
    }
}
