package week04;

public class IfWithoutElse {
    static void main() {
        boolean sunny = true;

        if (sunny) {
            System.out.println("Let's put on sunglasses and go out");
        }

        int batteryLevel = 15;

        if (batteryLevel < 20) {
            System.out.println("Battery low!");
        }
    }
}
